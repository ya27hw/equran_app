/// The tashkeel form of surah [surah] (1–114), or [fallback] when the number is
/// out of range.
String surahTitleTashkeel(int surah, {required String fallback}) {
  if (surah < 1 || surah > _surahTitlesTashkeel.length) return fallback;
  return _surahTitlesTashkeel[surah - 1];
}
